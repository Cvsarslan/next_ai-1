def _meta_rows(rows):
    """rows: list of (label, jinja_value_expr, optional_condition_expr)."""
    out = []
    for label, expr, cond in rows:
        line = '<tr><td class="k">%s</td><td class="v">{{ %s }}</td></tr>' % (label, expr)
        if cond:
            line = "{%% if %s %%}%s{%% endif %%}" % (cond, line)
        out.append(line)
    return '<div class="nx-meta-grid"><table>%s</table></div>' % "".join(out)


def _items_table(show_tax_columns=True):
    """Line items with optional per-line VAT amount column."""
    tax_th = '<th class="num">VAT</th>' if show_tax_columns else ""
    tax_td = (
        '<td class="num">{{ frappe.utils.fmt_money(row.get("tax_amount") or 0, currency=doc.currency) if row.get("tax_amount") else "—" }}</td>'
        if show_tax_columns else ""
    )
    return """
<table class="nx-items">
  <thead><tr>
    <th style="width:28px">#</th>
    <th>Description</th>
    <th class="num">Qty</th>
    <th>UOM</th>
    <th class="num">Rate</th>
    <th class="num">Amount</th>
    %s
  </tr></thead>
  <tbody>
  {%% for row in doc.items %%}
    <tr>
      <td>{{ loop.index }}</td>
      <td><b>{{ row.get("item_name") or row.get("item_code") }}</b>
        {%% if row.get("description") and row.description != row.get("item_name") %%}<div style="color:#64748b;font-size:10px">{{ row.description | striptags }}</div>{%% endif %%}
      </td>
      <td class="num">{{ row.qty }}</td>
      <td>{{ row.get("uom") or row.get("stock_uom") or "" }}</td>
      <td class="num">{{ frappe.utils.fmt_money(row.get("rate") or 0, currency=doc.currency) }}</td>
      <td class="num">{{ frappe.utils.fmt_money(row.get("amount") or 0, currency=doc.currency) }}</td>
      %s
    </tr>
  {%% endfor %%}
  </tbody>
</table>
""" % (tax_th, tax_td)


def _totals(show_vat=True):
    """Totals block: net, discount, each VAT line, grand total, amount in words."""
    vat_lines = ""
    if show_vat:
        vat_lines = """
    {% for t in doc.get("taxes") or [] %}
      {% if (t.tax_amount or 0) != 0 %}
      <tr><td class="k">{{ t.description }}</td><td class="v">{{ frappe.utils.fmt_money(t.tax_amount, currency=doc.currency) }}</td></tr>
      {% endif %}
    {% endfor %}
"""
    return """
<div class="nx-tot-wrap"><div class="nx-tot"><table>
  <tr><td class="k">Total (Excl. VAT)</td><td class="v">{{ frappe.utils.fmt_money(doc.get("net_total") or doc.get("total") or 0, currency=doc.currency) }}</td></tr>
  {%% if (doc.get("discount_amount") or 0) != 0 %%}<tr><td class="k">Discount</td><td class="v">- {{ frappe.utils.fmt_money(doc.discount_amount, currency=doc.currency) }}</td></tr>{%% endif %%}
  %s
  <tr class="grand"><td class="k">Grand Total</td><td class="v">{{ frappe.utils.fmt_money(doc.get("grand_total") or doc.get("rounded_total") or 0, currency=doc.currency) }}</td></tr>
  {%% if (doc.get("outstanding_amount") or 0) > 0 %%}<tr><td class="k">Outstanding</td><td class="v">{{ frappe.utils.fmt_money(doc.outstanding_amount, currency=doc.currency) }}</td></tr>{%% endif %%}
</table></div></div>
{%% if doc.get("in_words") %%}<div class="nx-words"><b>In words:</b> {{ doc.in_words }}</div>{%% endif %%}
""" % vat_lines


def _terms():
    return """
{% if doc.get("terms") %}<div class="nx-terms"><b>Terms &amp; Conditions</b>\n{{ doc.terms | striptags }}</div>{% endif %}
<div class="nx-sign"><div>Authorised Signatory</div><div>Received By</div></div>
"""


def _txn_format(title, party_type, meta_rows, show_vat=True):
    return (
        _CSS
        + '<div class="nx-doc">'
        + _HEADER
        + ('<div class="nx-title">%s</div>' % title)
        + '<div class="nx-meta-wrap">'
        + _party_box(party_type)
        + _meta_rows(meta_rows)
        + "</div>"
        + _items_table(show_tax_columns=show_vat)
        + _totals(show_vat=show_vat)
        + _terms()
        + _FOOTER
        + "</div>"
    )


