def _upsert(name, doc_type, html):
    values = {
        "doctype": "Print Format",
        "name": name,
        "doc_type": doc_type,
        "module": MODULE,
        "standard": "No",
        "custom_format": 1,
        "print_format_type": "Jinja",
        "html": html,
        "font_size": 11,
        "margin_top": 12,
        "margin_bottom": 12,
        "margin_left": 12,
        "margin_right": 12,
        "disabled": 0,
    }
    if frappe.db.exists("Print Format", name):
        pf = frappe.get_doc("Print Format", name)
        pf.update(values)
        pf.save(ignore_permissions=True)
    else:
        frappe.get_doc(values).insert(ignore_permissions=True)


def install_uae_print_formats():
    """Create or refresh all UAE print formats. Safe to run repeatedly."""
    if not frappe.db.table_exists("Print Format"):
        return
    created = []
    for name, doc_type, html in _formats():
        try:
            _upsert(name, doc_type, html)
            created.append(name)
        except Exception:
            frappe.log_error(frappe.get_traceback(), "NextAI: install print format %s" % name)
    frappe.db.commit()
    return created


@frappe.whitelist()
def setup_uae_print_formats():
    """Whitelisted wrapper so the formats can be (re)installed from the UI/console."""
    frappe.only_for(("System Manager", "Administrator"))
    return install_uae_print_formats()
